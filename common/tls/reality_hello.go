//go:build with_utls

package tls

import (
	"net"
	"slices"

	utls "github.com/metacubex/utls"
)

// newRealityUClient creates the uTLS client of a REALITY handshake.
//
// Xray-core servers since v26.9.8 only accept a ClientHello that offers an X25519MLKEM768 key
// share before the X25519 one (XTLS/REALITY@8cdf7bf), as Xray's own client and browsers do. The
// REALITY auth key is still derived from the plain X25519 share (KeyShareKeys.Ecdhe), which
// servers check first, so the hybrid share is only added to the hello and never replaces it.
//
// A fingerprint without a fixed spec (randomized) is used as is.
func newRealityUClient(conn net.Conn, config *utls.Config, id utls.ClientHelloID) (*utls.UConn, error) {
	spec, err := utls.UTLSIdToSpec(id)
	if err != nil {
		return utls.UClient(conn, config, id), nil
	}
	addHybridKeyShare(&spec)
	uConn := utls.UClient(conn, config, utls.HelloCustom)
	err = uConn.ApplyPreset(&spec)
	if err != nil {
		return nil, err
	}
	return uConn, nil
}

// addHybridKeyShare makes the spec offer X25519MLKEM768 right before X25519 in the supported
// groups and in the key shares. A spec that has no X25519 is left alone: REALITY cannot use it.
func addHybridKeyShare(spec *utls.ClientHelloSpec) {
	for _, extension := range spec.Extensions {
		switch extension := extension.(type) {
		case *utls.SupportedCurvesExtension:
			if slices.Contains(extension.Curves, utls.X25519MLKEM768) {
				continue
			}
			index := slices.Index(extension.Curves, utls.X25519)
			if index < 0 {
				continue
			}
			extension.Curves = slices.Insert(slices.Clone(extension.Curves), index, utls.X25519MLKEM768)
		case *utls.KeyShareExtension:
			if slices.ContainsFunc(extension.KeyShares, func(share utls.KeyShare) bool {
				return share.Group == utls.X25519MLKEM768
			}) {
				continue
			}
			index := slices.IndexFunc(extension.KeyShares, func(share utls.KeyShare) bool {
				return share.Group == utls.X25519
			})
			if index < 0 {
				continue
			}
			// the key data is generated by utls
			extension.KeyShares = slices.Insert(slices.Clone(extension.KeyShares), index, utls.KeyShare{Group: utls.X25519MLKEM768})
		}
	}
}
